#!/usr/bin/env python3
"""Pick labelled samples from Wikimedia Commons and append them to test/real-samples.txt.

    python3 test/commons_samples.py [--per-generator 2] [--real 24] [--per-artist 2]
    python3 test/make_fixtures.py --fetch
    node test/accuracy.mjs

AI images come from per-generator categories ("Images generated by Midjourney", ...);
real images are camera photos from several curated categories (quality, valued and
featured pictures), with at most --per-artist files from any one uploader. It uses Commons'
1600px thumbnails, which are re-encoded without metadata, like most images on the web,
so the results measure the model rather than the metadata check.

Each line is preceded by a comment with the title, author, licence and file page.
Commons categories are curated by volunteers, so check any surprising result on the
file page before blaming the detector.
"""

import argparse
import json
import re
import time
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path

API = "https://commons.wikimedia.org/w/api.php"
UA = "aihound-test-fixtures/0.1 (sample collection script)"
OUT = Path(__file__).resolve().parent / "real-samples.txt"

GENERATORS = [
    "Images generated by Adobe Firefly AI",
    "Images generated by ChatGPT",
    "Images generated by DALL-E",
    "Images generated by Flux (text-to-image model)",
    "Images generated by Gemini",
    "GPT Image",
    "Images generated by Grok",
    "Images generated by Imagen",
    "Images generated by Midjourney",
    "Images generated by Nano Banana",
    "Images generated by Stable Diffusion",
    "Images generated by thispersondoesnotexist.com",
]
REAL_CATEGORIES = ["Quality images", "Valued images sorted by promotion date", "Featured pictures on Wikimedia Commons"]
MIMES = {"image/jpeg", "image/png", "image/webp"}


def api(**params):
    params = {"format": "json", "formatversion": "2", **params}
    req = urllib.request.Request(f"{API}?{urllib.parse.urlencode(params)}", headers={"User-Agent": UA})
    for attempt in range(6):
        try:
            with urllib.request.urlopen(req, timeout=30) as r:
                time.sleep(1)  # be polite to the API
                return json.load(r)
        except urllib.error.HTTPError as e:
            if e.code != 429 or attempt == 5:
                raise
            wait = int(e.headers.get("Retry-After") or 5 * 2 ** attempt)
            print(f"  rate limited, waiting {wait}s")
            time.sleep(wait)


def files_in(category, limit, mimes, sort_recent=False, per_artist=2, max_pages=5):
    params = dict(
        action="query", generator="categorymembers", gcmtitle=f"Category:{category}", gcmtype="file",
        gcmlimit="100", prop="imageinfo", iiprop="url|mime|size|extmetadata", iiurlwidth="1600",
        iiextmetadatafilter="LicenseShortName|Artist",
    )
    if sort_recent:
        params.update(gcmsort="timestamp", gcmdir="desc")
    picked, by_artist = [], {}
    for _ in range(max_pages):
        data = api(**params)
        for page in data.get("query", {}).get("pages", []):
            f = pick(page, mimes)
            if not f or by_artist.get(f["artist"], 0) >= per_artist:
                continue
            by_artist[f["artist"]] = by_artist.get(f["artist"], 0) + 1
            picked.append(f)
            if len(picked) >= limit:
                return picked
        if "continue" not in data:
            break
        params.update(data["continue"])
    return picked


def pick(page, mimes):
    info = (page.get("imageinfo") or [{}])[0]
    if info.get("mime") not in mimes or min(info.get("width", 0), info.get("height", 0)) < 512:
        return None
    meta = info.get("extmetadata", {})
    artist = re.sub(r"<[^>]+>", "", meta.get("Artist", {}).get("value", "unknown")).strip()
    return {
            "title": page["title"],
            "url": info.get("thumburl") or info["url"],
            "page": info.get("descriptionurl", ""),
            "license": meta.get("LicenseShortName", {}).get("value", "unknown"),
            "artist": artist[:80],
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--per-generator", type=int, default=2)
    ap.add_argument("--real", type=int, default=24)
    ap.add_argument("--per-artist", type=int, default=2)
    args = ap.parse_args()

    existing = OUT.read_text() if OUT.exists() else ""
    lines = ["", "# ---- Wikimedia Commons samples (test/commons_samples.py) ----"]
    counts = {"ai": 0, "real": 0}

    def add(label, f, group):
        if f["url"] in existing:
            return
        comment = " | ".join([group, f["title"], f["artist"], f["license"], f["page"]])
        lines.append("# " + re.sub(r"\s+", " ", comment))
        lines.append(f"{label} {f['url']}")
        counts[label] += 1

    for cat in GENERATORS:
        found = files_in(cat, args.per_generator, MIMES, per_artist=args.per_artist)
        print(f"{len(found)} from {cat}")
        for f in found:
            add("ai", f, cat.replace("Images generated by ", ""))
    per_cat = -(-args.real // len(REAL_CATEGORIES))
    for cat in REAL_CATEGORIES:
        found = files_in(cat, per_cat, {"image/jpeg"}, sort_recent=True, per_artist=args.per_artist)
        print(f"{len(found)} from {cat}")
        for f in found:
            add("real", f, "camera photo")

    with OUT.open("a") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"appended {counts['ai']} ai + {counts['real']} real samples to {OUT}")


if __name__ == "__main__":
    main()
